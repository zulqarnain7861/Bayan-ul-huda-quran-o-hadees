  /**
   * Additional content-only languages (where Quran translations are verified & available offline,
   * while the app interface honestly remains in English rather than claiming full UI localization).
   */
  val contentOnlyLanguages: List<AppInterfaceLanguage> by lazy {
    val supportedCodes = supportedInterfaceLanguages.map { it.code.lowercase() }.toSet()
    QulTranslationCatalog.languageGroups
      .filter { !it.isMissingInSource && it.languageCode.lowercase() !in supportedCodes }
      .map { group ->
        val firstEd = group.editions.first()
        AppInterfaceLanguage(
          code = group.languageCode,
          nameEnglish = group.languageNameEn,
          nameNative = group.languageNameNative,
          isRtl = group.isRtl,
          isInterfaceComplete = false,
          scriptInfo = if (group.isRtl) "RTL Script" else "LTR Script",
          regionOrCategory = "CONTENT_ONLY",
          defaultSunniQuranEditionKey = firstEd.editionKey,
          defaultShiaQuranEditionKey = "en.qarai",
          quranEditionsSummary = "${group.editions.size} Verified Edition(s): ${group.editions.joinToString { it.translatorName }}",
          licenseAndSourceSummary = "QUL / Quran.com / fawazahmed0 (Offline Quran Content • Interface uses English)"
        )
      }
  }

  fun findInterfaceLanguage(code: String): AppInterfaceLanguage {
    val clean = code.lowercase().trim()
    return supportedInterfaceLanguages.find { it.code.equals(clean, ignoreCase = true) }
      ?: contentOnlyLanguages.find { it.code.equals(clean, ignoreCase = true) }
      ?: supportedInterfaceLanguages.first()
  }

